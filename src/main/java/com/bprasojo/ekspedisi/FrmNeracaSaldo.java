    private void isiCBTahun() {
        
        for (int i = 2020; i < 2090; i++) {
            cbTahun.addItem(i);
        }
        
        // Mendapatkan tahun sekarang
        int tahunSekarang = java.time.LocalDate.now().getYear();

        // Menyetel item yang dipilih dengan tahun sekarang
        cbTahun.setSelectedItem(tahunSekarang);  // Memilih tahun saat ini di ComboBox
    }

    private Date getTanggalTerakhirBulanSebelumnya(int tahun, int bulan) {
        // Membuat objek Calendar untuk tanggal pertama bulan yang diberikan
        Calendar calendar = Calendar.getInstance();
        calendar.set(Calendar.YEAR, tahun);
        calendar.set(Calendar.MONTH, bulan - 1);  // Bulan dimulai dari 0, jadi kurangi 1
        calendar.set(Calendar.DAY_OF_MONTH, 1);  // Set tanggal pertama bulan

        // Menentukan tanggal terakhir bulan sebelumnya
        calendar.add(Calendar.MONTH, -1);  // Pindah ke bulan sebelumnya
        calendar.set(Calendar.DAY_OF_MONTH, calendar.getActualMaximum(Calendar.DAY_OF_MONTH));  // Set ke hari terakhir bulan sebelumnya

        // Mengambil tanggal terakhir bulan sebelumnya sebagai java.util.Date
        return calendar.getTime();
    }

    private boolean IsTanggalSudahClosing(Date tanggalTerakhirBulanSebelumnya) {
        Date lastClosingDate;
        try {
            lastClosingDate = bukubesarDAO.getLastClosingDate();
            int dateClsoingInt = AppUtils.dateToInt(lastClosingDate);
            int dateTransInt  = AppUtils.dateToInt(tanggalTerakhirBulanSebelumnya);

            return dateTransInt <= dateClsoingInt;
        } catch (SQLException ex) {
            Logger.getLogger(FrmNeracaSaldo.class.getName()).log(Level.SEVERE, null, ex);
            return false;
        }
    }
